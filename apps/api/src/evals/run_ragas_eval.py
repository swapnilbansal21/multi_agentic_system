"""Phase 2 (runs in .venv-eval, NOT the main app venv): scores the
predictions generated by generate_rag_predictions.py using Ragas.

Run with: .venv-eval/Scripts/python.exe -m src.evals.run_ragas_eval
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from datasets import Dataset
from dotenv import load_dotenv
from langchain_openai import AzureChatOpenAI, AzureOpenAIEmbeddings
from ragas import evaluate
from ragas.embeddings import LangchainEmbeddingsWrapper
from ragas.llms import LangchainLLMWrapper
from ragas.metrics import answer_relevancy, context_precision, faithfulness

PREDICTIONS_PATH = Path(__file__).parent / "rag_eval_predictions.json"
RESULTS_PATH = Path(__file__).parent / "rag_eval_results.json"

FAITHFULNESS_THRESHOLD = 0.80  # spec §14 CI gate


def load_predictions() -> Dataset:
    records = json.loads(PREDICTIONS_PATH.read_text())
    return Dataset.from_list(
        [
            {
                "user_input": r["question"],
                "response": r["answer"],
                "retrieved_contexts": r["contexts"] or [""],
                "reference": r["ground_truth"],
            }
            for r in records
        ]
    )


def main() -> None:
    load_dotenv(Path(__file__).parents[2] / ".env")

    judge_llm = LangchainLLMWrapper(
        AzureChatOpenAI(
            azure_endpoint=os.environ["AZURE_OPENAI_ENDPOINT"],
            api_key=os.environ["AZURE_OPENAI_API_KEY"],
            azure_deployment=os.environ.get("AZURE_OPENAI_DEPLOYMENT", "gpt-4o-main"),
            api_version=os.environ.get("AZURE_OPENAI_API_VERSION", "2024-10-21"),
        )
    )
    judge_embeddings = LangchainEmbeddingsWrapper(
        AzureOpenAIEmbeddings(
            azure_endpoint=os.environ["AZURE_OPENAI_ENDPOINT"],
            api_key=os.environ["AZURE_OPENAI_API_KEY"],
            azure_deployment=os.environ.get(
                "AZURE_OPENAI_EMBEDDING_DEPLOYMENT", "text-embedding-3-small"
            ),
        )
    )

    dataset = load_predictions()
    result = evaluate(
        dataset,
        metrics=[faithfulness, answer_relevancy, context_precision],
        llm=judge_llm,
        embeddings=judge_embeddings,
    )

    scores = result.to_pandas()
    RESULTS_PATH.write_text(scores.to_json(orient="records", indent=2))

    print(scores[["user_input", "faithfulness", "answer_relevancy", "context_precision"]])
    avg_faithfulness = scores["faithfulness"].mean()
    print(f"\nAverage faithfulness: {avg_faithfulness:.3f} (CI gate: >= {FAITHFULNESS_THRESHOLD})")

    if avg_faithfulness < FAITHFULNESS_THRESHOLD:
        raise SystemExit(f"FAILED: faithfulness {avg_faithfulness:.3f} < {FAITHFULNESS_THRESHOLD}")
    print("PASSED")


if __name__ == "__main__":
    main()
